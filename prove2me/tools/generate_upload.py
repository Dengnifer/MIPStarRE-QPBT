def theorem_natural(node: dict[str, Any], command: dict[str, Any]) -> str:
    body = TARGET_NATURAL.get(node["originalName"])
    if body is None:
        doc = clean_docstring(command["module"], command)
        summary = doc.split("\n\n", 1)[0] if doc else title_from_name(node["originalName"])
        summary = re.sub(r"`([^`]+)`", r"\1", summary)
        body = (
            f"{summary}\n\n"
            "All objects, parameters, typeclass assumptions, and hypotheses are quantified in "
            "the accompanying formal statement; each symbol denotes the object of the displayed "
            "Lean type with that name. The conclusion is the proposition"
            "\n\n$$\\text{asserted by the formal QPBT declaration.}$$\n\n"
            "This result is an importable reduction step in the formal dependency graph for the "
            "quantum Pauli basis test completeness or soundness argument."
        )
    return (
        body
        + f"\n\n**Formalization Credit.** {FORMALIZATION_CREDIT}"
        + f"\n\n**Mathematical Source.** {MATH_SOURCE}"
    )


def definition_natural(module: str, count: int) -> str:
    return (
        f"This private definition bundle contains {count} source commands from `{module}`. "
        "It preserves the exact data structures, operators, instances, and theorem-valued "
        "construction facts required by downstream QPBT declarations.\n\n"
        f"**Formalization Credit.** {FORMALIZATION_CREDIT}\n\n"
        f"**Mathematical Source.** {MATH_SOURCE}"
    )


def source_link(path: str, start: int | None = None, end: int | None = None) -> str:
    base = f"{SOURCE_REPO}/blob/{SOURCE_SHA}/{path}"
    if start is not None and end is not None:
        return f"{base}#L{start}-L{end}"
    return base


def generate() -> dict[str, Any]:
    plan = json.loads(PLAN_PATH.read_text(encoding="utf-8"))
    if not plan["lidt"]["resolved"]:
        raise RuntimeError("upload plan has no resolved LIDT map; rerun planner with --require-lidt-map")
    missing_context = []
    for module in plan["modules"]:
        path = context_path(module)
        source = source_path(module)
        if (
            not path.is_file()
            or path.stat().st_mtime_ns <= source.stat().st_mtime_ns
            or path.stat().st_mtime_ns <= CONTEXT_EXTRACTOR.stat().st_mtime_ns
        ):
            missing_context.append(module)
    if missing_context:
        raise RuntimeError(f"context extraction is incomplete for {len(missing_context)} modules")
    rewriter = Rewriter(plan)
    if OUT.exists():
        shutil.rmtree(OUT)
    for directory in (OUT / "Definitions", OUT / "Theorems", OUT / "Solutions"):
        directory.mkdir(parents=True, exist_ok=True)

    definition_payloads: list[dict[str, Any]] = []
    theorem_payloads: list[dict[str, Any]] = []
    solution_payloads: list[dict[str, Any]] = []
    for bundle_id in plan["definitionOrder"]:
        bundle = plan["definitions"][bundle_id]
        module = bundle["module"]
        imports = {
            *("Definitions.Def_" + plan["definitions"][dependency]["definitionName"]
              for dependency in bundle["definitionDependencies"]),
            *plan["modules"][module]["mathlibImports"],
            *bundle["lidtImports"],
        }
        body = skeleton_body(plan, module, set(bundle["commands"]), rewriter).decode("utf-8")
        text = (
            f"-- Generated from {bundle['source']} by skeleton subtraction.\n"
            + import_lines(imports)
            + external_namespace_preamble(plan, [module])
            + wrap_body(body, plan["uploadNamespace"])
        )
        path = OUT / "Definitions" / f"Def_{bundle['definitionName']}.lean"
        path.write_text(text, encoding="utf-8")
        definition_payloads.append({
            "bundle_id": bundle_id,
            "definition_name": bundle["definitionName"],
            "definition_title": f"QPBT definitions: {module.removeprefix('QPBT.').replace('.', ' / ')}",
            "definition_path": str(path.relative_to(ROOT)),
            "definition": text,
            "natural_language_statement": definition_natural(module, len(bundle["commands"])),
            "source": source_link(bundle["source"], *bundle["sourceLines"]),
            "tags": ["QPBT"],
            "private": True,
        })

    for command_id in plan["nodeOrder"]:
        node = plan["nodes"][command_id]
        command = plan["commands"][command_id]
        module = node["module"]
        definition_imports = {
            "Definitions.Def_" + plan["definitions"][bundle_id]["definitionName"]
            for bundle_id in node["definitionBundles"]
        }
        type_theorem_imports = {
            "Theorems.Thm_" + plan["nodes"][dependency]["slug"]
            for dependency in node["typeTheoremDependencies"]
        }
        theorem_imports = {
            "Theorems.Thm_" + plan["nodes"][dependency]["slug"]
            for dependency in node["theoremDependencies"]
        }
        preamble_imports = {
            *definition_imports,
            *type_theorem_imports,
            *plan["modules"][module]["mathlibImports"],
            *node["lidtTheoremImports"],
        }
        context = platformize_context(plan, module, command_id, rewriter)
        formal = extract_command(plan, command_id, node["platformName"], rewriter, stub=True)
        preamble = (
            import_lines(preamble_imports)
            + external_namespace_preamble(plan, [module])
            + context
        )
        theorem_text = preamble.rstrip() + "\n\n" + formal
        theorem_path = OUT / "Theorems" / f"Thm_{node['slug']}.lean"
        theorem_path.write_text(theorem_text, encoding="utf-8")

        inline_by_module: dict[str, set[str]] = defaultdict(set)
        helper_module_deps: dict[str, set[str]] = defaultdict(set)
        for inline_id in node["inlineCommands"]:
            inline_module = plan["commands"][inline_id]["module"]
            inline_by_module[inline_module].add(inline_id)
        inline_set = set(node["inlineCommands"])
        for inline_id in inline_set:
            inline_module = plan["commands"][inline_id]["module"]
            command = plan["commands"][inline_id]
            for dependency in set(command["typeCommandDeps"] + command["valueCommandDeps"]):
                if dependency not in inline_set:
                    continue
                dependency_module = plan["commands"][dependency]["module"]
                if dependency_module != inline_module:
                    helper_module_deps[inline_module].add(dependency_module)
        helper_modules = topo_modules(set(inline_by_module), helper_module_deps)
        helper_fragments: list[str] = []
        for inline_module in helper_modules:
            fragment = skeleton_body(
                plan, inline_module, inline_by_module[inline_module], rewriter
            ).decode("utf-8")
            fragment = wrap_body(fragment, plan["uploadNamespace"]).strip()
            if fragment:
                activations = "\n".join(local_instance_activations(
                    plan, inline_by_module[inline_module], rewriter
                ))
                helper_fragments.append(
                    f"/- Source helpers from {plan['modules'][inline_module]['source']}. -/\n"
                    + (activations + "\n" if activations else "")
                    + fragment
                )
        helper_mathlib = set(plan["modules"][module]["mathlibImports"])
        for inline_module in helper_modules:
            helper_mathlib.update(plan["modules"][inline_module]["mathlibImports"])
        solution_imports = {
            *definition_imports,
            *theorem_imports,
            *helper_mathlib,
            *node["lidtSolutionImports"],
        }
        solution_command = extract_command(
            plan, command_id, "solution", rewriter, stub=False
        )
        helpers = "\n\n".join(helper_fragments)
        solution_text = (
            f"-- Generated proof for {node['originalName']}.\n"
            + import_lines(solution_imports)
            + external_namespace_preamble(plan, [module, *helper_modules])
            + helpers
            + ("\n\n" if helpers else "")
            + context.rstrip()
            + "\n\n"
            + solution_command
        )
        solution_path = OUT / "Solutions" / f"Sol_{node['slug']}.lean"
        solution_path.write_text(solution_text, encoding="utf-8")

        source = source_link(node["source"], *node["sourceLines"])
        theorem_payloads.append({
            "command_id": command_id,
            "theorem_name": node["platformName"],
            "theorem_title": title_from_name(node["originalName"]),
            "preamble": preamble.rstrip(),
            "formal_statement": formal.rstrip(),
            "natural_language_statement": theorem_natural(node, command),
            "source": source,
            "tags": ["QPBT"],
            "private": True,
            "theorem_path": str(theorem_path.relative_to(ROOT)),
        })
        solution_payloads.append({
            "command_id": command_id,
            "theorem_name": node["platformName"],
            "solution_path": str(solution_path.relative_to(ROOT)),
            "explanation": (
                f"This submission transports the checked source proof of `{node['originalName']}` "
                "into the private QPBT dependency graph. It uses only mapped LIDT entries, "
                "Mathlib, and already verified child QPBT declarations, while preserving the "
                "source hypotheses and conclusion. " + FORMALIZATION_CREDIT
            ),
        })

    all_imports = [
        *("Definitions.Def_" + plan["definitions"][bundle_id]["definitionName"]
          for bundle_id in plan["definitionOrder"]),
        *("Theorems.Thm_" + plan["nodes"][command_id]["slug"]
          for command_id in plan["nodeOrder"]),
    ]
    (OUT / "All.lean").write_text(import_lines(all_imports), encoding="utf-8")
    payloads = {
        "schemaVersion": 2,
        "sourceCommit": SOURCE_SHA,
        "tag": "QPBT",
        "private": True,
        "definitions": definition_payloads,
        "theorems": theorem_payloads,
        "solutions": solution_payloads,
    }
    PAYLOADS.write_text(json.dumps(payloads, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return payloads


def main() -> int:
    payloads = generate()
    print(json.dumps({
        "definitions": len(payloads["definitions"]),
        "theorems": len(payloads["theorems"]),
        "solutions": len(payloads["solutions"]),
    }, sort_keys=True))
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"wrote {PAYLOADS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
