def generated_qpbt_name(original: str, wrapper: str) -> str:
    return f"{wrapper}.{original}" if wrapper else original


def platform_project_name(name: str) -> str:
    if (
        name == "MIPStarRE.LDT"
        or name.startswith("MIPStarRE.LDT.")
        or name == "MIPStarRE.Quantum"
        or name.startswith("MIPStarRE.Quantum.")
    ):
        return "LIDT." + name
    return name


class Rewriter:
    def __init__(self, plan: dict[str, Any]) -> None:
        self.wrapper = plan["uploadNamespace"]
        self.external = plan["externalNameMap"]
        self.project_names = plan["projectNameMap"]
        self.node_names = {
            node["originalName"]: node["platformName"] for node in plan["nodes"].values()
        }
        graph = read_jsonl(GRAPH_PATH)
        self.project_rows = {row["name"]: row for row in graph}
        self.deprivatized: dict[str, str] = {}
        for command_id, command in plan["commands"].items():
            if not command["deprivatize"]:
                continue
            for row_name in command["rows"]:
                row = self.project_rows[row_name]
                self.deprivatized[row_name] = self.project_names.get(
                    row["userName"], row["userName"]
                )
                if command_id in plan["nodes"]:
                    self.node_names[row_name] = plan["nodes"][command_id]["platformName"]

    def target(self, const: str) -> str | None:
        external = self.external.get(const)
        if external:
            return "_root_." + external
        node_target = self.node_names.get(const)
        if node_target:
            expected = generated_qpbt_name(const, self.wrapper)
            if node_target != expected or self.wrapper:
                return "_root_." + node_target
        deprivatized = self.deprivatized.get(const)
        if deprivatized:
            return "_root_." + deprivatized
        row = self.project_rows.get(const)
        if row is not None and row["userName"] in self.project_names:
            target = self.project_names[row["userName"]]
            if self.wrapper:
                target = self.wrapper + "." + target
            return "_root_." + target
        if self.wrapper and row is not None and not row["isPrivate"]:
            return "_root_." + self.wrapper + "." + row["userName"]
        if row is not None and not row["isPrivate"]:
            return "_root_." + platform_project_name(row["userName"])
        return None

    def replacement(self, const: str, data: bytes, start: int, end: int) -> str | None:
        target = self.target(const)
        if target is None:
            return None
        token = data[start:end].decode("utf-8")
        if token == "_":
            return None
        if token.startswith(".") and token[1:] == const.rsplit(".", 1)[-1]:
            return None
        line_start = data.rfind(b"\n", 0, start) + 1
        if (
            "." not in token
            and token == const.rsplit(".", 1)[-1]
            and re.search(rb"\|\s*@?\s*$", data[line_start:start])
        ):
            return None
        if start > 0 and data[start - 1:start] == b"." and "." not in token:
            leaf = target.rsplit(".", 1)[-1]
            return None if leaf == token else leaf
        return target


def mapped_external_open_name(name: str) -> str | None:
    if name == "MIPStarRE.LDT" or name.startswith("MIPStarRE.LDT."):
        return "LIDT." + name
    if name == "MIPStarRE.Quantum" or name.startswith("MIPStarRE.Quantum."):
        return "LIDT." + name
    return None


def mapped_open_name(name: str) -> str | None:
    return mapped_external_open_name(name)


@cache
def project_namespaces() -> set[str]:
    result: set[str] = set()
    for row in read_jsonl(GRAPH_PATH):
        pieces = row["userName"].split(".")
        result.update(".".join(pieces[:end]) for end in range(1, len(pieces)))
    return result


def namespace_anchors(plan: dict[str, Any], module: str) -> set[str]:
    result: set[str] = set()
    namespace_stack: list[str] = []
    frame_stack: list[tuple[str, int]] = []
    known = project_namespaces()
    data = source_bytes(module)
    for fact in context_facts(module):
        kind = fact["kind"]
        if kind == "namespace":
            name = fact["name"]
            pieces = name.removeprefix("_root_.").split(".")
            old_size = len(namespace_stack)
            if name.startswith("_root_."):
                namespace_stack[:] = pieces
            else:
                namespace_stack.extend(pieces)
            frame_stack.append(("namespace", old_size))
            full = ".".join(namespace_stack)
            mapped = mapped_external_open_name(full)
            if mapped:
                result.add(mapped)
            elif full in known:
                local = platform_project_name(full)
                wrapper = plan["uploadNamespace"]
                result.add(f"{wrapper}.{local}" if wrapper else local)
        elif kind == "section":
            frame_stack.append(("section", len(namespace_stack)))
        elif kind == "end":
            if not frame_stack:
                continue
            frame_kind, old_size = frame_stack.pop()
            if frame_kind == "namespace":
                del namespace_stack[old_size:]
        elif kind == "openName":
            start = fact["range"]["start"]["offset"]
            line_start = data.rfind(b"\n", 0, start) + 1
            line_prefix = data[line_start:start].decode("utf-8")
            if re.match(r"\s*open\s+scoped\b", line_prefix) or re.search(
                r"\bhiding\b", line_prefix
            ):
                continue
            name = fact["name"]
            mapped = mapped_external_open_name(name)
            if mapped:
                result.add(mapped)
                continue
            bare = name.removeprefix("_root_.")
            candidates = [bare] if name.startswith("_root_.") else [
                ".".join([*namespace_stack[:end], bare])
                for end in range(len(namespace_stack), -1, -1)
            ]
            local = next((candidate for candidate in candidates if candidate in known), None)
            if local:
                local = platform_project_name(local)
                wrapper = plan["uploadNamespace"]
                result.add(f"{wrapper}.{local}" if wrapper else local)
    return result


def extension_namespace_edits(
    module: str,
    lower: int,
    upper: int,
    removed_decl_ranges: Iterable[tuple[int, int]],
) -> list[tuple[int, int, bytes]]:
    removed = list(removed_decl_ranges)
    edits: list[tuple[int, int, bytes]] = []
    frames: list[tuple[str, bool]] = []
    for fact in context_facts(module):
        kind = fact["kind"]
        if kind == "declHead" or kind == "openName" or kind == "include":
            continue
        offsets = range_offsets(fact.get("range"))
        if offsets is None:
            continue
        start, end = offsets
        if kind == "namespace":
            mapped = mapped_external_open_name(fact["name"]) is not None
            frames.append(("namespace", mapped))
            if (
                mapped and lower <= start and end <= upper
                and not any(a <= start and end <= b for a, b in removed)
            ):
                edits.append((start, start, b"namespace LIDT\n"))
        elif kind == "section":
            frames.append(("section", False))
        elif kind == "end":
            if not frames:
                raise RuntimeError(f"unmatched end while mapping namespaces in {module}")
            frame_kind, mapped = frames.pop()
            if (
                frame_kind == "namespace" and mapped
                and lower <= start and end <= upper
                and not any(a <= start and end <= b for a, b in removed)
            ):
                edits.append((end, end, b"\nend LIDT"))
    return edits


def external_namespace_preamble(plan: dict[str, Any], modules: Iterable[str]) -> str:
    names = sorted({
        name for module in modules for name in namespace_anchors(plan, module)
    })
    if not names:
        return ""
    return "\n".join(f"namespace {name}\nend {name}" for name in names) + "\n\n"


def binding_ref(
    module: str,
    command: dict[str, Any],
    original_name: str,
    *,
    required: bool = True,
) -> dict[str, Any] | None:
    data = source_bytes(module)
    _, refs = facts_for(module)
    start, end = plan_command_key(command)
    name_text = original_name.rsplit(".", 1)[-1]
    candidates: list[dict[str, Any]] = []
    for ref in refs:
        ref_start = ref["start"]["offset"]
        ref_end = ref["end"]["offset"]
        if not (start <= ref_start < ref_end <= end):
            continue
        token = data[ref_start:ref_end].decode("utf-8")
        const = ref["const"]
        if (
            const == original_name
            or token == name_text
            or token.endswith("." + name_text)
        ):
            candidates.append(ref)
    if not candidates:
        if required:
            raise RuntimeError(f"no binding reference for {original_name} in {module}")
        return None
    candidates.sort(key=lambda ref: ref["start"]["offset"])
    return candidates[0]


def selected_binding_ranges(
    plan: dict[str, Any], module: str, selected_ids: set[str], rewriter: Rewriter
) -> set[tuple[int, int]]:
    result: set[tuple[int, int]] = set()
    for command_id in selected_ids:
        command = plan["commands"][command_id]
        originals: set[str] = set()
        if command_id in plan["nodes"]:
            originals.add(plan["nodes"][command_id]["originalName"])
        for row_name in command["rows"]:
            graph_row = rewriter.project_rows.get(row_name)
            if graph_row:
                originals.add(graph_row["userName"])
        for original in originals:
            fact = binding_ref(module, command, original, required=False)
            if fact:
                result.add((fact["start"]["offset"], fact["end"]["offset"]))
    return result


def empty_context_ranges(
    module: str, selected_keys: set[tuple[int, int]]
) -> list[tuple[int, int]]:
    frames: list[tuple[str, int]] = []
    empty: list[tuple[int, int]] = []
    for fact in context_facts(module):
        kind = fact["kind"]
        offsets = range_offsets(fact.get("range"))
        if kind in {"namespace", "section"} and offsets is not None:
            frames.append((kind, offsets[0]))
        elif kind == "end" and offsets is not None:
            if not frames:
                raise RuntimeError(f"unmatched end while pruning contexts in {module}")
            _, start = frames.pop()
            end = offsets[1]
            if not any(start <= decl_start and decl_end <= end
                       for decl_start, decl_end in selected_keys):
                empty.append((start, end))
    outermost: list[tuple[int, int]] = []
    for start, end in sorted(empty, key=lambda item: (item[0], -item[1])):
        if not any(parent_start <= start and end <= parent_end
                   for parent_start, parent_end in outermost):
            outermost.append((start, end))
    return outermost


def syntax_bound_ref_ranges(module: str) -> list[tuple[int, int]]:
    data = source_bytes(module)
    result: list[tuple[int, int]] = []
    for fact in context_facts(module):
        if fact["kind"] != "openName":
            continue
        offsets = range_offsets(fact.get("range"))
        if offsets is None:
            continue
        start, end = offsets
        line_start = data.rfind(b"\n", 0, start) + 1
        if re.search(rb"\bhiding\b", data[line_start:start]):
            result.append((start, end))
    return result


def anonymous_local_instance_edits(
    plan: dict[str, Any], module: str, selected_ids: set[str]
) -> list[tuple[int, int, bytes]]:
    facts = {
        (fact["declStart"]["offset"], fact["declEnd"]["offset"]): fact
        for fact in context_facts(module)
        if fact["kind"] == "declHead"
    }
    edits: list[tuple[int, int, bytes]] = []
    for command_id in selected_ids:
        command = plan["commands"][command_id]
        if not command.get("isLocalInstance", False) or command["nameText"] is not None:
            continue
        fact = facts.get(plan_command_key(command))
        if fact is None or fact.get("nameInsert") is None:
            raise RuntimeError(
                f"anonymous local instance has no parser insertion point: {command_id}"
            )
        anchor = command.get("anchor")
        if anchor is None:
            raise RuntimeError(f"anonymous local instance has no anchor: {command_id}")
        position = fact["nameInsert"]["offset"]
        edits.append((position, position, f" {anchor.rsplit('.', 1)[-1]}".encode()))
    return edits


def proof_prologue_edits(
    plan: dict[str, Any], module: str, selected_ids: Iterable[str]
) -> list[tuple[int, int, bytes]]:
    data = source_bytes(module)
    edits: list[tuple[int, int, bytes]] = []
    marker = b":= by\n"
    for command_id in selected_ids:
        command = plan["commands"][command_id]
        prologue = PROOF_PROLOGUES.get(command.get("anchor"))
        if prologue is None:
            continue
        value = command.get("valStart")
        if value is None:
            raise RuntimeError(f"proof prologue command has no value: {command_id}")
        start = value["offset"]
        if data[start:start + len(marker)] != marker:
            raise RuntimeError(f"unsupported proof prologue syntax: {command_id}")
        position = start + len(marker)
        edits.append((position, position, prologue.encode()))
    return edits


def skeleton_body(
    plan: dict[str, Any],
    module: str,
    selected_ids: set[str],
    rewriter: Rewriter,
) -> bytes:
    data = source_bytes(module)
    body_start = plan["modules"][module]["headerEnd"]["offset"]
    decls, refs = facts_for(module)
    selected_keys = {
        plan_command_key(plan["commands"][command_id]) for command_id in selected_ids
    }
    empty_contexts = empty_context_ranges(module, selected_keys)
    dropped_commands = [
        offsets for fact in context_facts(module)
        if fact["kind"] == "dropCommand"
        for offsets in [range_offsets(fact.get("range"))]
        if offsets is not None
        and not any(a <= offsets[0] and offsets[1] <= b for a, b in empty_contexts)
    ]
    deprivatize_keys = {
        plan_command_key(plan["commands"][command_id])
        for command_id in selected_ids
        if plan["commands"][command_id]["deprivatize"]
    }
    edits: list[tuple[int, int, bytes]] = []
    removed_decl_ranges: list[tuple[int, int]] = []
    for fact in decls:
        start, end = command_key(fact)
        if (start, end) not in selected_keys:
            if not any(a <= start and end <= b for a, b in empty_contexts):
                edits.append((start, end, b""))
            removed_decl_ranges.append((start, end))
        elif (start, end) in deprivatize_keys:
            private_range = range_offsets(fact["privateTok"])
            if private_range:
                edits.append((*private_range, b""))
    binding_ranges = selected_binding_ranges(plan, module, selected_ids, rewriter)
    syntax_ranges = syntax_bound_ref_ranges(module)
    removed_ranges = [*removed_decl_ranges, *empty_contexts, *dropped_commands]
    ref_edits: list[tuple[int, int, bytes]] = []
    for ref in refs:
        start = ref["start"]["offset"]
        end = ref["end"]["offset"]
        if any(ranges_overlap((start, end), binding) for binding in binding_ranges):
            continue
        if any(ranges_overlap((start, end), syntax) for syntax in syntax_ranges):
            continue
        if any(a <= start and end <= b for a, b in removed_ranges):
            continue
        target = rewriter.replacement(ref["const"], data, start, end)
        if target:
            ref_edits.append((start, end, target.encode()))
    edits.extend(minimal_ref_edits(ref_edits))
    for fact in context_facts(module):
        if fact["kind"] != "openName":
            continue
        target = mapped_open_name(fact["name"])
        offsets = range_offsets(fact["range"])
        if (
            target and offsets and offsets[0] >= body_start
            and not any(start <= offsets[0] and offsets[1] <= end
                        for start, end in removed_ranges)
        ):
            edits.append((*offsets, target.encode()))
    edits.extend(anonymous_local_instance_edits(plan, module, selected_ids))
    edits.extend(proof_prologue_edits(plan, module, selected_ids))
    edits.extend(extension_namespace_edits(
        module, body_start, len(data), removed_ranges
    ))
    edits.extend((start, end, b"") for start, end in dropped_commands)
    edits.extend((start, end, b"") for start, end in empty_contexts)
    transformed = apply_edits(data, edits)
    return transformed[body_start:]


def qualified_namespace(name: str, namespace_stack: list[str], wrapper: str) -> str:
    if name.startswith("_root_."):
        pieces = name.removeprefix("_root_.")
    else:
        pieces = ".".join([*namespace_stack, name])
    pieces = platform_project_name(pieces)
    return f"{wrapper}.{pieces}" if wrapper else pieces


def qualified_open_name(
    plan: dict[str, Any], name: str, namespace_stack: list[str]
) -> str | None:
    mapped = mapped_open_name(name)
    if mapped:
        return mapped
    bare = name.removeprefix("_root_.")
    candidates = [bare] if name.startswith("_root_.") else [
        ".".join([*namespace_stack[:end], bare])
        for end in range(len(namespace_stack), -1, -1)
    ]
    local = next(
        (candidate for candidate in candidates if candidate in project_namespaces()),
        None,
    )
    if local is None:
        return None
    local = platform_project_name(local)
    wrapper = plan["uploadNamespace"]
    return f"{wrapper}.{local}" if wrapper else local


def local_instance_activations(
    plan: dict[str, Any], command_ids: Iterable[str], rewriter: Rewriter
) -> list[str]:
    dependencies = {
        dependency
        for command_id in command_ids
        for dependency in plan["commands"][command_id]["typeCommandDeps"]
        if plan["commands"][dependency].get("isLocalInstance", False)
    }
    activations: set[str] = set()
    for dependency in dependencies:
        command = plan["commands"][dependency]
        anchor = command.get("anchor")
        if anchor is None:
            raise RuntimeError(f"local instance command has no anchor: {dependency}")
        target = rewriter.target(anchor)
        if target is None:
            raise RuntimeError(f"local instance has no platform name: {anchor}")
        activations.add(f"attribute [local instance] {target}")
    return sorted(activations)


def platformize_context(
    plan: dict[str, Any], module: str, command_id: str, rewriter: Rewriter
) -> str:
    target_command = plan["commands"][command_id]
    target_start = target_command["declStart"]["offset"]
    data = source_bytes(module)
    body_start = plan["modules"][module]["headerEnd"]["offset"]
    decls, refs = facts_for(module)
    edits: list[tuple[int, int, bytes]] = []
    removed_decl_ranges: list[tuple[int, int]] = []
    for fact in decls:
        start, end = command_key(fact)
        if end <= target_start:
            edits.append((start, end, b""))
            removed_decl_ranges.append((start, end))
        elif start < target_start:
            raise RuntimeError(f"target starts inside another declaration in {module}")
    namespace_stack: list[str] = []
    frame_stack: list[tuple[str, int]] = []
    for fact in context_facts(module):
        if fact["kind"] == "declHead":
            continue
        offsets = range_offsets(fact["range"])
        if offsets is None:
            continue
        start, end = offsets
        if start >= target_start:
            break
        kind = fact["kind"]
        if kind == "namespace":
            name = fact["name"]
            full = qualified_namespace(name, namespace_stack, plan["uploadNamespace"])
            edits.append((start, end, f"open {full}".encode()))
            pieces = name.removeprefix("_root_.").split(".")
            old_size = len(namespace_stack)
            if name.startswith("_root_."):
                namespace_stack[:] = pieces
            else:
                namespace_stack.extend(pieces)
            frame_stack.append(("namespace", old_size))
        elif kind == "section":
            edits.append((start, end, b""))
            frame_stack.append(("section", len(namespace_stack)))
        elif kind == "end":
            edits.append((start, end, b""))
            if not frame_stack:
                raise RuntimeError(f"unmatched end before target in {module}")
            frame_kind, old_size = frame_stack.pop()
            if frame_kind == "namespace":
                del namespace_stack[old_size:]
        elif kind == "include":
            pass
        elif kind == "dropCommand":
            edits.append((start, end, b""))
        elif kind == "openName":
            line_start = data.rfind(b"\n", 0, start) + 1
            line_prefix = data[line_start:start]
            if re.match(rb"\s*open\s+scoped\b", line_prefix) or re.search(
                rb"\bhiding\b", line_prefix
            ):
                continue
            target = qualified_open_name(plan, fact["name"], namespace_stack)
            if target and not any(a <= start and end <= b for a, b in removed_decl_ranges):
                edits.append((start, end, target.encode()))
    structural_ranges = [(start, end) for start, end, _ in edits if start < end]
    syntax_ranges = syntax_bound_ref_ranges(module)
    ref_edits: list[tuple[int, int, bytes]] = []
    for ref in refs:
        start = ref["start"]["offset"]
        end = ref["end"]["offset"]
        if not (body_start <= start < end <= target_start):
            continue
        if any(a <= start and end <= b for a, b in removed_decl_ranges):
            continue
        if any(ranges_overlap((start, end), syntax) for syntax in syntax_ranges):
            continue
        if any(ranges_overlap((start, end), structural) for structural in structural_ranges):
            continue
        target = rewriter.replacement(ref["const"], data, start, end)
        if target:
            ref_edits.append((start, end, target.encode()))
    edits.extend(minimal_ref_edits(ref_edits))
    prefix_data = data[body_start:target_start]
    prefix = apply_edits(prefix_data, [
        (start - body_start, end - body_start, replacement)
        for start, end, replacement in edits
        if body_start <= start and end <= target_start
    ])
    activations = local_instance_activations(plan, [command_id], rewriter)
    context = prefix.decode("utf-8").strip()
    return "\n".join([part for part in [context, *activations] if part]) + "\n"


def extract_command(
    plan: dict[str, Any],
    command_id: str,
    binding: str,
    rewriter: Rewriter,
    *,
    stub: bool,
) -> str:
    command = plan["commands"][command_id]
    node = plan["nodes"][command_id]
    module = command["module"]
    data = source_bytes(module)
    start, end = plan_command_key(command)
    cutoff = command["valStart"]["offset"] if stub else end
    edits: list[tuple[int, int, bytes]] = []
    doc_range = range_offsets(command["docstring"])
    if doc_range:
        edits.append((*doc_range, b""))
    private_range = range_offsets(command["privateTok"])
    if private_range:
        edits.append((*private_range, b""))
    head_facts = [
        fact for fact in context_facts(module)
        if fact["kind"] == "declHead"
        and fact["declStart"]["offset"] == start
        and fact["declEnd"]["offset"] == end
    ]
    if len(head_facts) != 1:
        raise RuntimeError(
            f"expected one exact declaration-head fact for {node['originalName']}; "
            f"found {len(head_facts)}"
        )
    head = head_facts[0]
    keyword_range = range_offsets(head["keywordRange"])
    if keyword_range is None:
        raise RuntimeError(f"missing declaration keyword range for {node['originalName']}")
    anchor = command.get("anchor")
    anchor_row = rewriter.project_rows.get(anchor) if anchor else None
    if anchor_row and anchor_row["isInstance"]:
        edits.append((*keyword_range, b"@[instance] theorem"))
    elif head["keyword"] != "theorem":
        edits.append((*keyword_range, b"theorem"))
    protected_range = range_offsets(head["protectedTok"])
    if protected_range:
        edits.append((*protected_range, b""))
    binding_fact = binding_ref(module, command, node["originalName"])
    assert binding_fact is not None
    binding_range = (
        binding_fact["start"]["offset"], binding_fact["end"]["offset"]
    )
    edits.append((*binding_range, binding.encode()))
    _, refs = facts_for(module)
    syntax_ranges = syntax_bound_ref_ranges(module)
    ref_edits: list[tuple[int, int, bytes]] = []
    for ref in refs:
        ref_start = ref["start"]["offset"]
        ref_end = ref["end"]["offset"]
        if ranges_overlap((ref_start, ref_end), binding_range):
            continue
        if any(ranges_overlap((ref_start, ref_end), syntax) for syntax in syntax_ranges):
            continue
        if not (start <= ref_start < ref_end <= cutoff):
            continue
        target = rewriter.replacement(ref["const"], data, ref_start, ref_end)
        if target:
            ref_edits.append((ref_start, ref_end, target.encode()))
    edits.extend(minimal_ref_edits(ref_edits))
    if not stub:
        edits.extend(proof_prologue_edits(plan, module, [command_id]))
    segment = apply_edits(data[start:cutoff], [
        (edit_start - start, edit_end - start, replacement)
        for edit_start, edit_end, replacement in edits
        if start <= edit_start and edit_end <= cutoff
    ]).decode("utf-8")
    if stub:
        segment = segment.rstrip() + " := by sorry"
    return segment.strip() + "\n"


def wrap_body(body: str, wrapper: str) -> str:
    body = body.strip()
    if not wrapper:
        return body + ("\n" if body else "")
    return f"namespace {wrapper}\n\n{body}\n\nend {wrapper}\n"


def title_from_name(name: str) -> str:
    leaf = name.rsplit(".", 1)[-1]
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", leaf).replace("_", " ").split()
    return " ".join(word.capitalize() if word.islower() else word for word in words)[:200]


def clean_docstring(module: str, command: dict[str, Any]) -> str:
    doc_range = range_offsets(command["docstring"])
    if not doc_range:
        return ""
    data = source_bytes(module)
    value = data[doc_range[0]:doc_range[1]].decode("utf-8")
    value = re.sub(r"^/--\s*", "", value)
    value = re.sub(r"\s*-/\s*$", "", value)
    return value.strip()


